class PlayerStreamTrack(MediaStreamTrack):
    """
    A video track that returns an animated flag.
    """

    def __init__(self, player, kind):
        super().__init__()  # don't forget this!
        self.kind = kind
        self._player = player
        self._queue = asyncio.Queue(maxsize=100)
        self.timelist = [] #记录最近包的时间戳
        self.current_frame_count = 0
        if self.kind == 'video':
            self.framecount = 0
            self.lasttime = time.perf_counter()
            self.totaltime = 0
    
    _start: float
    _timestamp: int

    async def next_timestamp(self, source_timestamp=None) -> Tuple[int, fractions.Fraction]:
        if self.readyState != "live":
            raise Exception
        video = self.kind == 'video'
        clock_rate = VIDEO_CLOCK_RATE if video else SAMPLE_RATE
        time_base = VIDEO_TIME_BASE if video else AUDIO_TIME_BASE
        interval = VIDEO_PTIME if video else AUDIO_PTIME
        if source_timestamp is None:
            timestamp = self._timestamp + int(interval * clock_rate) if hasattr(self, '_timestamp') else 0
        else:
            timestamp = source_timestamp

        now = time.monotonic()
        if not hasattr(self, '_start'):
            self._start = now
            self._origin_timestamp = timestamp
        wait = self._start + (timestamp - self._origin_timestamp) / clock_rate - now
        if wait > 0:
            await asyncio.sleep(wait)
        self._timestamp = timestamp
        self.current_frame_count += 1
        return timestamp, time_base

    async def recv(self) -> Union[Frame, Packet]:        
        self._player._start(self)

        frame,eventpoint = await self._queue.get()
        if frame is None:
            self.stop()
            raise Exception
        # Sparse idle video must retain the audio clock, not advance only 40 ms.
        source_timestamp = None
        if self.kind == 'video' and frame.pts is not None and frame.time_base is not None:
            source_timestamp = int(frame.pts * frame.time_base * VIDEO_CLOCK_RATE)
        pts, time_base = await self.next_timestamp(source_timestamp)
        frame.pts = pts
        frame.time_base = time_base
        if eventpoint and self._player is not None:
            self._player.notify(eventpoint)
        if self.kind == 'video':
            self.totaltime += (time.perf_counter() - self.lasttime)
            self.framecount += 1
            self.lasttime = time.perf_counter()
            if self.framecount==100:
                mylogger.info(f"------actual avg final fps:{self.framecount/self.totaltime:.4f}")
                self.framecount = 0
                self.totaltime=0
        return frame
    
    def stop(self):
        super().stop()
        # Drain & delete remaining frames
        while not self._queue.empty():
            item = self._queue.get_nowait()
            del item
        if self._player is not None:
            self._player._stop(self)
            self._player = None

def player_worker_thread(
    quit_event,
    loop,
    container,
    audio_track,
    video_track
):
    container.render(quit_event,loop,audio_track,video_track)

class HumanPlayer:

    def __init__(
        self, avatar_stream, format=None, options=None, timeout=None, loop=False, decode=True
    ):
        self.__thread: Optional[threading.Thread] = None
        self.__thread_quit: Optional[threading.Event] = None

        # examine streams
        self.__started: Set[PlayerStreamTrack] = set()
        self.__audio: Optional[PlayerStreamTrack] = None
        self.__video: Optional[PlayerStreamTrack] = None

        self.__audio = PlayerStreamTrack(self, kind="audio")
        self.__video = PlayerStreamTrack(self, kind="video")

        self.__container = avatar_stream

    def notify(self,eventpoint):
        if self.__container is not None:
            self.__container.notify(eventpoint)

    @property
    def audio(self) -> MediaStreamTrack:
        """
        A :class:`aiortc.MediaStreamTrack` instance if the file contains audio.
        """
        return self.__audio

    @property
    def video(self) -> MediaStreamTrack:
        """
        A :class:`aiortc.MediaStreamTrack` instance if the file contains video.
        """
        return self.__video

    def _start(self, track: PlayerStreamTrack) -> None:
        self.__started.add(track)
        if self.__thread is None:
            self.__log_debug("Starting worker thread")
            self.__thread_quit = threading.Event()
            self.__thread = threading.Thread(
                name="media-player",
                target=player_worker_thread,
                args=(
                    self.__thread_quit,
                    asyncio.get_event_loop(),
                    self.__container,
                    self.__audio,
                    self.__video                   
                ),
            )
            self.__thread.start()

    def _stop(self, track: PlayerStreamTrack) -> None:
        self.__started.discard(track)

        if not self.__started and self.__thread is not None:
            self.__log_debug("Stopping worker thread")
            self.__thread_quit.set()
            self.__thread.join()
            self.__thread = None

        if not self.__started and self.__container is not None:
            #self.__container.close()
            self.__container = None

    def __log_debug(self, msg: str, *args) -> None:
        mylogger.debug(f"HumanPlayer {msg}", *args)
